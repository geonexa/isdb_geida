"""
Write the Analyses section of the documentation (docs/analyses/) from the analyses themselves: each manifest
(question, phases, CRIs, inputs, settings, outputs, workflow steps) and METHOD.md (method, data, outputs,
limitations). Run it after adding or changing an analysis, so the documentation matches the code:

    python manage.py document_analyses              # writes docs/analyses/*.md
    python manage.py document_analyses --check      # exits with an error if the pages are out of date
"""
import re
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from apps.analysis.core.registry import analysis_folders, read_categories, read_manifests

GENERATED = "<!-- Generated by `python manage.py document_analyses` from the manifests and METHOD.md files. Don't edit by hand. -->"
TYPE_LABEL = {"raster": "Raster", "vector_point": "Points", "vector_line": "Lines", "vector_polygon": "Polygons",
              "vector": "Vector", "table": "Table"}
OUT_LABEL = {"metric": "Figure", "table": "Table", "raster": "Raster map (GeoTIFF + map)", "vector": "Map layer (GeoJSON)",
             "image": "Map image", "file": "Download"}


def docs_dir():
    return Path(settings.BASE_DIR).parent / "docs" / "analyses"


def method_sections(folder):
    """{section title: markdown} from an analysis' METHOD.md (headings two levels down)."""
    path = Path(folder) / "METHOD.md" if folder else None
    if not path or not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    parts = re.split(r"^## +(.+)$", text, flags=re.M)
    return {title.strip(): body.strip() for title, body in zip(parts[1::2], parts[2::2])}


def _cell(v):
    return str(v).replace("|", "\\|").replace("\n", " ")


def dataset_info(ds_id):
    from apps.analysis.data import DATASETS
    ds = DATASETS.get(ds_id)
    if ds is None:
        return "", ""
    d = ds.describe()
    return d.get("title") or ds_id, d.get("resolution") or ""


def step_text(step):
    if isinstance(step, dict):
        return "; ".join(f"**{k.replace('_', ' ')}**: {_steps_value(v)}" for k, v in step.items())
    return str(step)


def _steps_value(v):
    if isinstance(v, list):
        return ", ".join(map(str, v))
    if isinstance(v, dict):
        return ", ".join(f"{k}: {x}" for k, x in v.items()) or "—"
    return str(v)


def analysis_page_section(m, folder):
    sec = method_sections(folder)
    out = [f"## {m['title']}", "", f"**Question:** {m.get('question', '')}", ""]
    if m.get("description"):
        out += [" ".join(str(m["description"]).split()), ""]

    inputs = [(i, "required") for i in (m.get("inputs") or {}).get("required", []) or []] + \
             [(i, "optional") for i in (m.get("inputs") or {}).get("optional", []) or []]
    if inputs:
        out += ["### Input data", "", "| Input | Kind | Dataset | Resolution | Needed |", "|---|---|---|---|---|"]
        for i, need in inputs:
            title, res = dataset_info(i.get("default", ""))
            out.append(f"| {_cell(i.get('label') or i['name'])} | {TYPE_LABEL.get(i.get('type'), i.get('type', ''))} | "
                       f"{_cell(title or i.get('default', ''))} | {_cell(res)} | {need} |")
        out.append("")
    params = m.get("parameters") or []
    if params:
        out += ["### Settings", "", "| Setting | Type | Default | Options |", "|---|---|---|---|"]
        for p in params:
            if p.get("type") == "choice":
                opts = "; ".join(str(c.get("label", c.get("value"))) for c in p.get("choices", []))
            elif p.get("type") == "number":
                opts = f"{p.get('min', '')}–{p.get('max', '')}".strip("–")
            elif p.get("type") == "point":
                opts = "picked on the map"
            else:
                opts = ""
            default = p.get("default")
            out.append(f"| {_cell(p.get('label') or p['name'])} | {p.get('type', '')} | "
                       f"{_cell('—' if default is None else default)} | {_cell(opts)} |")
        out.append("")
    steps = m.get("steps") or []
    if steps:
        out += ["### Workflow", ""] + [f"{n}. {step_text(s)}" for n, s in enumerate(steps, start=1)] + [""]
    if sec.get("Method"):
        out += ["### Method", "", sec["Method"], ""]
    if sec.get("Outputs"):
        out += ["### Outputs", "", sec["Outputs"], ""]
    else:
        outs = m.get("outputs") or []
        if outs:
            out += ["### Outputs", "", "| Output | Kind |", "|---|---|"]
            out += [f"| `{o['name']}` | {OUT_LABEL.get(o['type'], o['type'])} |" for o in outs] + [""]
    if sec.get("Data"):
        out += ["### Data sources and licences", "", sec["Data"], ""]
    if sec.get("Limitations"):
        out += ["### Limitations", "", sec["Limitations"], ""]
    cites = m.get("citations") or []
    if cites:
        out += ["### Citations", ""] + [f"- {c}" for c in cites] + [""]
    out += [f"Source: `backend/analyses/{m['category']}/{m['id']}/`", "", "---", ""]
    return "\n".join(out)


def build_pages():
    errors = []
    manifests = read_manifests(errors)
    if errors:
        raise CommandError("Fix the analyses first: " + "; ".join(errors))
    folders = analysis_folders()
    cats = sorted(read_categories(), key=lambda c: c.get("order", 99))
    by_cat = {c["id"]: [] for c in cats}
    for m in manifests.values():
        by_cat.setdefault(m["category"], []).append(m)
    pages = {}
    index = [GENERATED, "", "# Analyses", "",
             "Analyses answer questions about a project's area of influence from Earth observation and map data: how "
             "steep the land is, where water drains, what covers the land, how many people live there, what is built. "
             "Each one reads open datasets for the area, processes them on the server and returns figures, tables, maps "
             "and downloads, with a record of the data and settings used. General GIS processing (buffer, clip, zonal "
             "statistics, reclassify…) is in the [Toolbox](../introduction/toolbox.md).", "",
             "Each page below explains every analysis in its category: the question it answers, the data it reads, "
             "its settings, how it turns the data into results (workflow and method), what it produces, and its "
             "limitations.", "",
             "| Category | Analyses | What it covers |", "|---|---|---|"]
    listing = ["", "## All analyses", "", "| Analysis | Category | Question |", "|---|---|---|"]
    for c in cats:
        mods = sorted(by_cat.get(c["id"], []), key=lambda m: m["title"])
        if not mods:
            continue
        slug = c["id"]
        index.append(f"| [{c['title']}]({slug}.md) | {len(mods)} | {_cell(c.get('description', ''))} |")
        body = [GENERATED, "", f"# {c['title']}", "", c.get("description", ""), "",
                "| Analysis | Question |", "|---|---|"]
        body += [f"| [{m['title']}](#{re.sub(r'[^a-z0-9 -]', '', m['title'].lower()).replace(' ', '-')}) | {_cell(m.get('question', ''))} |"
                 for m in mods]
        body += ["", "---", ""]
        for m in mods:
            body.append(analysis_page_section(m, folders.get(m["id"])))
            anchor = re.sub(r"[^a-z0-9 -]", "", m["title"].lower()).replace(" ", "-")
            listing.append(f"| [{m['title']}]({slug}.md#{anchor}) | {c['title']} | {_cell(m.get('question', ''))} |")
        pages[f"{slug}.md"] = "\n".join(body).rstrip() + "\n"
    index += listing
    index += ["", "To add an analysis, see [Adding an analysis module](../development/adding-a-module.md). These pages are "
              "generated from each analysis' `manifest.yaml` and `METHOD.md` with `python manage.py document_analyses`."]
    pages["index.md"] = "\n".join(index) + "\n"
    return pages


class Command(BaseCommand):
    help = "Write docs/analyses/ from the analyses' manifests and METHOD.md files."

    def add_arguments(self, parser):
        parser.add_argument("--check", action="store_true", help="Fail if the pages are out of date (for CI).")

    def handle(self, *args, check=False, **opts):
        pages = build_pages()
        out = docs_dir()
        if check:
            stale = [n for n, text in pages.items() if not (out / n).exists() or (out / n).read_text() != text]
            if stale:
                raise CommandError(f"docs/analyses is out of date ({', '.join(stale)}). Run python manage.py document_analyses.")
            self.stdout.write("docs/analyses is up to date.")
            return
        out.mkdir(parents=True, exist_ok=True)
        for old in out.glob("*.md"):
            if old.name not in pages and GENERATED in old.read_text():
                old.unlink()
        for name, text in pages.items():
            (out / name).write_text(text, encoding="utf-8")
        self.stdout.write(f"Wrote {len(pages)} pages to {out}.")
